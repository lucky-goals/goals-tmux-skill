from __future__ import annotations

from pathlib import Path
import sys
import unittest

RUNTIME = Path(__file__).resolve().parents[1] / "runtime"
if str(RUNTIME) not in sys.path:
    sys.path.insert(0, str(RUNTIME))

from goals_tmux.setup_wizard import dump_yaml  # noqa: E402
from goals_tmux.workflow_edit import (  # noqa: E402
    MAX_DEPTH,
    MAX_DOCUMENT_BYTES,
    WorkflowEditError,
    parse_generated_yaml,
    patch_generated_yaml,
    validate_target,
)
from goals_tmux.workflow_template import new_workflow  # noqa: E402


class WorkflowEditTests(unittest.TestCase):
    def test_real_dump_round_trip_and_optional_yaml_compatibility(self) -> None:
        workflow = new_workflow()
        workflow["scenarios"]["research"].update(
            {"target": "codex/model-a", "fallbacks": [], "allow_fallback": False}
        )
        raw = dump_yaml(workflow, [("codex/model-a", "model")]).encode("utf-8")

        document = parse_generated_yaml(raw)

        self.assertEqual(document.raw, raw)
        self.assertEqual(document.workflow, workflow)
        self.assertIs(patch_generated_yaml(document, {}), raw)
        try:
            import yaml  # type: ignore[import-not-found]
        except ImportError:
            return
        self.assertEqual(yaml.safe_load(raw), workflow)

    def test_patch_changes_only_requested_routes(self) -> None:
        workflow = new_workflow()
        workflow["scenarios"]["research"].update(
            {"target": "codex/old", "fallbacks": [], "allow_fallback": False, "operator_note": "keep # text"}
        )
        workflow["scenarios"]["review"]["target"] = "codex/old"
        workflow["extension"] = {"quote": '雪 # still text', "nested": [[], {}, {"x": 3}]}
        raw = dump_yaml(workflow).encode("utf-8")
        raw = raw.replace(
            b'    "target": "codex/old"\n',
            b'    "target": "codex/old" # retain this route comment\n',
            1,
        )
        root_start = raw.index(b'"scenarios":')
        review_start = raw.index(b'  "review":', root_start)
        raw = raw[:review_start] + b"    # keep route comment\n" + raw[review_start:]
        document = parse_generated_yaml(raw)

        updated = patch_generated_yaml(
            document,
            {
                "research": {
                    "target": 'codex/model "quoted"',
                    "fallbacks": ["claude/模型/high"],
                    "allow_fallback": True,
                    "permission_mode": "bypass",
                },
                "review": {"target": 'codex/model "quoted"'},
            },
        )

        edited = parse_generated_yaml(updated)
        self.assertEqual(edited.workflow["scenarios"]["research"]["target"], 'codex/model "quoted"')
        self.assertEqual(edited.workflow["scenarios"]["research"]["fallbacks"], ["claude/模型/high"])
        self.assertEqual(edited.workflow["scenarios"]["research"]["permission_mode"], "bypass")
        self.assertEqual(edited.workflow["scenarios"]["research"]["operator_note"], "keep # text")
        self.assertEqual(edited.workflow["scenarios"]["review"]["fallbacks"], [])
        self.assertEqual(edited.workflow["extension"], workflow["extension"])
        self.assertIn(b"# Generated by the Goals tmux workflow setup wizard.\n", updated)
        self.assertIn(b"# keep route comment\n", updated)
        self.assertIn(b"# retain this route comment\n", updated)
        self.assertIn(b'"operator_note": "keep # text"', updated)

    def test_crlf_is_preserved_during_patch(self) -> None:
        raw = dump_yaml(new_workflow()).replace("\n", "\r\n").encode("utf-8")
        document = parse_generated_yaml(raw)
        updated = patch_generated_yaml(
            document,
            {"research": {"target": "codex/model-a", "fallbacks": [], "allow_fallback": False}},
        )

        self.assertEqual(
            parse_generated_yaml(updated).workflow["scenarios"]["research"]["target"],
            "codex/model-a",
        )
        self.assertIn(b'"target": "codex/model-a"\r\n', updated)
        self.assertNotIn(b"\n", updated.replace(b"\r\n", b""))

    def test_changed_fallback_span_keeps_comments(self) -> None:
        workflow = new_workflow()
        workflow["scenarios"]["research"].update(
            {"target": "codex/primary", "fallbacks": ["codex/backup"], "allow_fallback": True}
        )
        raw = dump_yaml(workflow).encode("utf-8")
        raw = raw.replace(
            b'    "fallbacks":\n      - "codex/backup"\n',
            b'    "fallbacks":\n      # keep this fallback note\n      - "codex/backup" # and this item note\n',
            1,
        )
        document = parse_generated_yaml(raw)

        updated = patch_generated_yaml(
            document,
            {"research": {"fallbacks": [], "allow_fallback": False}},
        )

        self.assertIn(b"# keep this fallback note\n", updated)
        self.assertIn(b"# and this item note\n", updated)
        self.assertEqual(parse_generated_yaml(updated).workflow["scenarios"]["research"]["fallbacks"], [])

    def test_target_grammar_validation(self) -> None:
        # Valid 2-segment target
        cli, model, effort = validate_target("claude/claude-opus-5-5")
        self.assertEqual((cli, model, effort), ("claude", "claude-opus-5-5", None))

        # Valid 3-segment target
        cli, model, effort = validate_target("claude/claude-opus-5-5/high")
        self.assertEqual((cli, model, effort), ("claude", "claude-opus-5-5", "high"))

        # Invalid forms
        invalid_forms = [
            "",
            "claude",
            "claude/opus/high/extra",
            "/opus",
            "claude/",
            "claude//high",
            " /opus",
            "claude/ ",
            "claude/ /high",
            123,
            None,
        ]
        for form in invalid_forms:
            with self.subTest(form=form):
                with self.assertRaises(WorkflowEditError):
                    validate_target(form)

    def test_v1_rejection_message(self) -> None:
        valid_v2 = dump_yaml(new_workflow()).encode("utf-8")
        v1_raw = valid_v2.replace(b'"schema_version": 2', b'"schema_version": 1', 1)
        with self.assertRaisesRegex(WorkflowEditError, "scripts/setup-workflow.sh"):
            parse_generated_yaml(v1_raw)

        v3_raw = valid_v2.replace(b'"schema_version": 2', b'"schema_version": 3', 1)
        with self.assertRaisesRegex(WorkflowEditError, "scripts/setup-workflow.sh"):
            parse_generated_yaml(v3_raw)

    def test_legacy_profiles_and_cli_defaults_rejection(self) -> None:
        valid = dump_yaml(new_workflow()).encode("utf-8")
        with_profiles = valid + b'"profiles": {}\n'
        with self.assertRaisesRegex(WorkflowEditError, "legacy format.*scripts/setup-workflow.sh"):
            parse_generated_yaml(with_profiles)

        with_cli_defaults = valid + b'"cli_defaults": {}\n'
        with self.assertRaisesRegex(WorkflowEditError, "legacy format.*scripts/setup-workflow.sh"):
            parse_generated_yaml(with_cli_defaults)

    def test_duplicate_fallbacks_and_primary_in_fallbacks_rejected(self) -> None:
        workflow = new_workflow()
        # Primary in fallbacks
        workflow["scenarios"]["research"].update({
            "target": "codex/model-a",
            "fallbacks": ["codex/model-a"],
            "allow_fallback": True,
        })
        raw = dump_yaml(workflow).encode("utf-8")
        with self.assertRaisesRegex(WorkflowEditError, "repeat the primary target"):
            parse_generated_yaml(raw)

        # Duplicate fallbacks
        workflow["scenarios"]["research"].update({
            "target": "codex/model-a",
            "fallbacks": ["codex/model-b", "codex/model-b"],
            "allow_fallback": True,
        })
        raw = dump_yaml(workflow).encode("utf-8")
        with self.assertRaisesRegex(WorkflowEditError, "not contain duplicates"):
            parse_generated_yaml(raw)

    def test_null_target_rules(self) -> None:
        workflow = new_workflow()
        # Null target with non-empty fallbacks
        workflow["scenarios"]["research"].update({
            "target": None,
            "fallbacks": ["codex/model-a"],
            "allow_fallback": True,
        })
        raw = dump_yaml(workflow).encode("utf-8")
        with self.assertRaisesRegex(WorkflowEditError, "target null requires empty fallbacks"):
            parse_generated_yaml(raw)

        # Null target with allow_fallback true
        workflow["scenarios"]["research"].update({
            "target": None,
            "fallbacks": [],
            "allow_fallback": True,
        })
        raw = dump_yaml(workflow).encode("utf-8")
        with self.assertRaisesRegex(WorkflowEditError, "target null requires allow_fallback false"):
            parse_generated_yaml(raw)

        # Null target with bypass permission_mode
        workflow["scenarios"]["research"].update({
            "target": None,
            "fallbacks": [],
            "allow_fallback": False,
            "permission_mode": "bypass",
        })
        raw = dump_yaml(workflow).encode("utf-8")
        with self.assertRaisesRegex(WorkflowEditError, "must be 'default' when target is null"):
            parse_generated_yaml(raw)

    def test_rejects_unsupported_syntax_and_missing_fields(self) -> None:
        valid = dump_yaml(new_workflow()).encode("utf-8")
        bad_documents = [
            valid.replace(b'"kind": "goals-tmux-workflow"', b'"kind": !tag "goals-tmux-workflow"', 1),
            valid.replace(b'"kind": "goals-tmux-workflow"', b'"kind": &anchor "goals-tmux-workflow"', 1),
            valid.replace(b'"kind": "goals-tmux-workflow"', b'"kind": *alias', 1),
            valid.replace(b'"kind": "goals-tmux-workflow"', b'"kind": [one, two]', 1),
            valid.replace(b'"kind": "goals-tmux-workflow"', b'"kind": |', 1),
            valid + b'"kind": "goals-tmux-workflow"\n',
            valid.replace(b'"kind": "goals-tmux-workflow"', b'"schema_version": 2\n"kind": "goals-tmux-workflow"', 1),
            valid.replace(b'"schema_version": 2', b'"schema_version": true', 1),
            valid.replace(b'    "target": null', b'    "target": "missing"', 1),
        ]
        for raw in bad_documents:
            with self.subTest(raw=raw[:80]):
                with self.assertRaises(WorkflowEditError):
                    parse_generated_yaml(raw)

    def test_size_depth_and_tab_indentation_bounds(self) -> None:
        with self.assertRaisesRegex(WorkflowEditError, "exceeds"):
            parse_generated_yaml(b"#" + b"x" * MAX_DOCUMENT_BYTES)
        with self.assertRaisesRegex(WorkflowEditError, "nesting exceeds"):
            workflow = new_workflow()
            value: dict[str, object] = {"leaf": "value"}
            for index in range(MAX_DEPTH + 2):
                value = {f"level-{index}": value}
            workflow["deep"] = value
            parse_generated_yaml(dump_yaml(workflow).encode("utf-8"))
        with self.assertRaisesRegex(WorkflowEditError, "tab indentation"):
            parse_generated_yaml(dump_yaml(new_workflow()).replace('"kind"', '\t"kind"', 1).encode("utf-8"))

    def test_invalid_requested_routes_are_rejected_without_returning_output(self) -> None:
        document = parse_generated_yaml(dump_yaml(new_workflow()).encode("utf-8"))
        invalid_edits = [
            {"research": {"target": "invalid"}},
            {"research": {"target": "codex/a", "fallbacks": ["invalid"], "allow_fallback": True}},
            {"research": {"target": "codex/a", "fallbacks": ["codex/b", "codex/b"], "allow_fallback": True}},
            {"research": {"other": "x"}},
        ]
        for update in invalid_edits:
            with self.subTest(update=update):
                with self.assertRaises(WorkflowEditError):
                    patch_generated_yaml(document, update)


if __name__ == "__main__":
    unittest.main()
